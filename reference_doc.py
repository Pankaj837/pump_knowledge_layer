"""Generate docs/KNOWLEDGE_BASE.md directly from the graph, so documentation never drifts from the data."""

from __future__ import annotations

from pathlib import Path

import networkx as nx

from graph_builder import in_neighbors, nodes_of_type, out_neighbors
from ontology import ONTOLOGY_SCHEMA, NodeType, Relation


def _limits(d: dict) -> str:
    return " / ".join("-" if d.get(k) is None else f"{d[k]:g}" for k in ("lo_lo", "lo", "hi", "hi_hi"))


def _signature(g: nx.DiGraph, owner: str, relation: Relation) -> str:
    parts = []
    for sym in out_neighbors(g, owner, relation):
        e, s = g.edges[owner, sym], g.nodes[sym]
        parts.append(f"{'**' if e['key_symptom'] else ''}{s['key']} {s['state']}{'**' if e['key_symptom'] else ''}"
                     f" (w{e['weight']:g})")
    return ", ".join(parts) or "- (no sensor evidence)"


def write_reference(g: nx.DiGraph, path: str | Path) -> Path:
    eq = g.graph["primary_equipment"]
    lines = [
        f"# Knowledge base reference - {eq}",
        "",
        "_Auto-generated by `python main.py` from the knowledge graph. Do not edit by hand._",
        "",
        f"Graph size: **{g.number_of_nodes()} nodes, {g.number_of_edges()} edges**.",
        "",
        "## Ontology schema (allowed relations)",
        "",
        "| Relation | Domain | Range |",
        "|---|---|---|",
    ]
    for rel, (dom, rng) in ONTOLOGY_SCHEMA.items():
        lines.append(f"| `{rel.value}` | {', '.join(sorted(t.value for t in dom))} | {', '.join(sorted(t.value for t in rng))} |")

    lines += ["", "## Equipment and components", "", "| Id | Class | Asset path |", "|---|---|---|"]
    for t in (NodeType.EQUIPMENT, NodeType.COMPONENT):
        for n in nodes_of_type(g, t):
            d = g.nodes[n]
            lines.append(f"| {n} | {d.get('equipment_class') or d.get('component_class')} | `{d['asset_path']}` |")

    lines += ["", "## Pump nameplate parameters", ""]
    lines += [f"- `{k}`: {v}" for k, v in g.nodes[eq]["parameters"].items()]

    lines += ["", "## Sensors", "", "Limits are LL / L / H / HH.", "",
              "| Tag | Signal key | Name | Unit | Limits | Monitors / derived from |", "|---|---|---|---|---|---|"]
    for t in (NodeType.SENSOR, NodeType.VIRTUAL_SENSOR):
        for n in nodes_of_type(g, t):
            d = g.nodes[n]
            target = ", ".join(out_neighbors(g, n, Relation.MONITORS) or out_neighbors(g, n, Relation.DERIVED_FROM))
            lines.append(f"| {n} | `{d['key']}` | {d['name']} | {d['unit']} | {_limits(d)} | {target} |")

    lines += ["", "## Failure modes", "", "Key symptoms (necessary conditions) are in **bold**; w = weight.", ""]
    for fm in nodes_of_type(g, NodeType.FAILURE_MODE):
        d = g.nodes[fm]
        lines += [f"### {fm} - {d['name']} ({d['severity']})", "",
                  f"- **Occurs in:** {', '.join(out_neighbors(g, fm, Relation.OCCURS_IN))}",
                  f"- **Signature:** {_signature(g, fm, Relation.MANIFESTS_AS)}",
                  f"- **Physics:** {d['physics']}",
                  f"- **Root causes:** {', '.join(in_neighbors(g, fm, Relation.CAUSES))}"]
        if out_neighbors(g, fm, Relation.PROPAGATES_TO):
            lines.append(f"- **Propagates to:** {', '.join(out_neighbors(g, fm, Relation.PROPAGATES_TO))}")
        lines.append("")

    lines += ["## Root causes", "", "| Id | Name | Causes | Evidence | Located in | Prior |", "|---|---|---|---|---|---|"]
    for rc in nodes_of_type(g, NodeType.ROOT_CAUSE):
        d = g.nodes[rc]
        lines.append(f"| {rc} | {d['name']} | {', '.join(out_neighbors(g, rc, Relation.CAUSES))} | "
                     f"{_signature(g, rc, Relation.EVIDENCED_BY)} | "
                     f"{', '.join(out_neighbors(g, rc, Relation.LOCATED_IN)) or '-'} | {d['prior']} |")

    lines += ["", "## Maintenance actions", "", "| Id | Type | Description |", "|---|---|---|"]
    for a in nodes_of_type(g, NodeType.ACTION):
        lines.append(f"| {a} | {g.nodes[a]['action_type']} | {g.nodes[a]['name']} |")

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
