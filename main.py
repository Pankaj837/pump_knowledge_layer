"""
End-to-end demo of the P-101 knowledge layer.

    python main.py                         # build graph, export, run all scenarios
    python main.py --scenario seal_leak    # run one scenario and print the report
    python main.py --readings '{"flow": 2, "discharge_pressure": 1.1, "motor_current": 13}'
    python main.py --scenario impeller_wear --json      # raw JSON result
    python main.py --scenario impeller_wear --llm       # grounded LLM prompt (Phase 4)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from diagnostic_engine import default_graph, diagnose_fault, format_report
from graph_builder import draw_graph, export_json, export_turtle
from llm_context import build_llm_context
from reference_doc import write_reference
from scenarios import SCENARIOS

ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "output"


def build_artifacts() -> None:
    g = default_graph()
    print(f"Knowledge graph: {g.number_of_nodes()} nodes, {g.number_of_edges()} edges (ontology-validated)")
    for p in (export_json(g, OUTPUT / "knowledge_graph.json"), export_turtle(g, OUTPUT / "knowledge_graph.ttl"),
              write_reference(g, ROOT / "docs" / "KNOWLEDGE_BASE.md"), write_example_prompt()):
        print(f"  wrote {p.relative_to(ROOT)}")
    try:
        for p in draw_graph(g, ROOT / "docs" / "figures"):
            print(f"  wrote {p.relative_to(ROOT)}")
    except ImportError:
        print("  matplotlib not installed - skipped PNG figures")


def write_example_prompt(scenario: str = "cavitation_clogged_strainer") -> Path:
    """Save one grounded LLM prompt in docs/ so reviewers can read it without running the code."""
    s = next(s for s in SCENARIOS if s.name == scenario)
    path = ROOT / "docs" / "EXAMPLE_LLM_PROMPT.md"
    path.write_text(f"# Example grounded LLM prompt\n\nScenario `{s.name}`: {s.description}\n\n"
                    f"Generated by `python main.py` with `build_llm_context()` (see `llm_context.py`).\n\n"
                    f"```text\n{build_llm_context(diagnose_fault(s.sensor_states))}\n```\n", encoding="utf-8")
    return path


def run_all_scenarios() -> bool:
    print(f"\n{'Scenario':<36} {'Status':<15} {'Primary failure mode':<25} {'Top root cause':<28} Check")
    print("-" * 113)
    all_ok = True
    for s in SCENARIOS:
        result = diagnose_fault(s.sensor_states)
        primary = next((d for d in result["diagnoses"] if d["role"] == "PRIMARY"), None)
        top_rc = primary["root_causes"][0]["id"] if primary and primary["root_causes"] else None
        ok = (result["status"] == s.expected_status
              and (primary["id"] if primary else None) == s.expected_primary
              and top_rc == s.expected_root_cause)
        all_ok &= ok
        label = f"{primary['id']} ({primary['confidence']:.2f})" if primary else "-"
        print(f"{s.name:<36} {result['status']:<15} {label:<25} {top_rc or '-':<28} {'PASS' if ok else 'FAIL'}")

        for sub, text, ext in (("reports", format_report(result), "txt"),
                               ("diagnoses", json.dumps(result, indent=2), "json"),
                               ("llm_context", build_llm_context(result), "md")):
            path = OUTPUT / sub / f"{s.name}.{ext}"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text + "\n", encoding="utf-8")
    print(f"\nPer-scenario reports, JSON results and LLM prompts written to {OUTPUT.relative_to(ROOT)}/")
    return all_ok


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Centrifugal pump P-101 knowledge layer demo")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--scenario", choices=[s.name for s in SCENARIOS], help="run one predefined scenario")
    group.add_argument("--readings", help="JSON object of sensor readings, e.g. '{\"flow\": 50}'")
    parser.add_argument("--json", action="store_true", help="print the raw JSON result")
    parser.add_argument("--llm", action="store_true", help="print the grounded LLM prompt (Phase 4)")
    args = parser.parse_args(argv)

    if args.scenario or args.readings:
        if args.scenario:
            scenario = next(s for s in SCENARIOS if s.name == args.scenario)
            print(f"Scenario: {scenario.name} - {scenario.description}\n")
            readings = scenario.sensor_states
        else:
            readings = json.loads(args.readings)
        result = diagnose_fault(readings)
        print(json.dumps(result, indent=2) if args.json else build_llm_context(result) if args.llm
              else format_report(result))
        return 0

    build_artifacts()
    return 0 if run_all_scenarios() else 1


if __name__ == "__main__":
    sys.exit(main())
